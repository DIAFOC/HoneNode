#!/usr/bin/env python3
"""Start a rootless, loopback-only app preview; never install or start a host broker."""

from __future__ import annotations

import argparse
import os
import re
import secrets
import stat
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

from build_image import APP_GID, APP_UID, DEFAULT_IMAGE, BuildError, Runner, run

RUN_DIR = Path(__file__).absolute().parents[1] / ".local-run"
BOOTSTRAP_KEYS = {"HONE_OPERATOR_ACCOUNT", "HONE_OPERATOR_PASSWORD"}


def check_digit(payload: str) -> str:
    total = 0
    for index, digit in enumerate(reversed(payload)):
        value = int(digit) * (2 if index % 2 == 0 else 1)
        total += value - 9 if value > 9 else value
    return str((-total) % 10)


def valid_account(number: str) -> bool:
    return bool(re.fullmatch(r"[0-9]{12}", number)) and check_digit(number[:-1]) == number[-1]


def new_account() -> str:
    payload = "".join(str(secrets.randbelow(10)) for _ in range(11))
    return payload + check_digit(payload)


def no_symlink_path(path: Path) -> Path:
    path = path.absolute()
    for component in (*reversed(path.parents), path):
        if component.is_symlink():
            raise BuildError(f"symlinks are not allowed in this path: {path}")
    return path


def private_directory(path: Path) -> None:
    no_symlink_path(path)
    path.mkdir(mode=0o700, exist_ok=True)
    metadata = path.lstat()
    if (not stat.S_ISDIR(metadata.st_mode) or metadata.st_uid != os.geteuid()
            or stat.S_IMODE(metadata.st_mode) != 0o700):
        raise BuildError(f"directory must be owned by you with mode 0700: {path}")


def read_bootstrap(path: Path) -> dict[str, str]:
    no_symlink_path(path)
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "r", encoding="utf-8") as source:
        metadata = os.fstat(source.fileno())
        if (not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.geteuid()
                or stat.S_IMODE(metadata.st_mode) != 0o600 or metadata.st_size > 8192):
            raise BuildError(f"bootstrap file must be your regular mode-0600 file, at most 8 KiB: {path}")
        values = {}
        for line in source.read(8193).split("\n"):
            if not line or line.startswith("#"):
                continue
            key, separator, value = line.partition("=")
            if (not separator or key not in BOOTSTRAP_KEYS or key in values
                    or any(ord(char) < 32 or ord(char) == 127 for char in value)):
                raise BuildError("bootstrap file requires unique, unquoted HONE_OPERATOR_ACCOUNT/PASSWORD entries")
            values[key] = value
    if "HONE_OPERATOR_ACCOUNT" in values and not valid_account(values["HONE_OPERATOR_ACCOUNT"]):
        raise BuildError("bootstrap account must be 12 ASCII digits with a valid Luhn check digit")
    if "HONE_OPERATOR_PASSWORD" in values and not 12 <= len(values["HONE_OPERATOR_PASSWORD"].encode()) <= 1024:
        raise BuildError("bootstrap password must be 12 to 1024 UTF-8 bytes")
    return values


def prepare_state(run_dir: Path, bootstrap_env: Path | None,
                  *, app_first_run: bool = False) -> tuple[Path, Path | None]:
    """Prepare private lab state.

    With app_first_run the operator credentials are generated by the app
    itself on first boot (shown once in the journal and written to
    <data>/registry/bootstrap-credentials.txt), so no bootstrap.env is created
    or imported. An existing bootstrap.env is refused: that state belongs to
    the imported-credentials flow.
    """
    private_directory(run_dir)
    data = run_dir / "data"
    private_directory(data)
    for name in ("registry", "tenants"):
        private_directory(data / name)
    if app_first_run:
        if (run_dir / "bootstrap.env").exists():
            raise BuildError(
                "this state directory already has bootstrap.env; run without --app-first-run "
                "or use a fresh --state-dir"
            )
        return data, None
    destination = run_dir / "bootstrap.env"
    supplied = read_bootstrap(bootstrap_env) if bootstrap_env is not None else {}
    if destination.exists() or destination.is_symlink():
        persisted = read_bootstrap(destination)
        if set(persisted) != BOOTSTRAP_KEYS:
            raise BuildError("saved bootstrap is incomplete; restore it rather than regenerating credentials")
        if any(persisted[key] != value for key, value in supplied.items()):
            raise BuildError("provided bootstrap differs from saved credentials; this is not a password-reset tool")
        return data, destination
    if (data / "registry" / "registry.db").exists():
        raise BuildError("registry already exists but bootstrap.env is missing; restore your saved credentials")
    values = {"HONE_OPERATOR_ACCOUNT": supplied.get("HONE_OPERATOR_ACCOUNT") or new_account(),
              "HONE_OPERATOR_PASSWORD": supplied.get("HONE_OPERATOR_PASSWORD") or secrets.token_urlsafe(32)}
    fd = os.open(destination, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as target:
        target.write("".join(f"{key}={values[key]}\n" for key in sorted(values)))
    return data, destination


def broker_directory(path: Path) -> Path:
    path = no_symlink_path(path)
    if not path.is_dir() or not stat.S_ISSOCK((path / "broker.sock").lstat().st_mode):
        raise BuildError("--broker-dir must contain a real broker.sock Unix socket")
    return path


def podman_command(*, image: str, name: str, data: Path, env_file: Path,
                   broker_dir: Path | None) -> list[str]:
    for path in (data, env_file, broker_dir):
        if path is not None and any(char in str(path) for char in (":", ",", "\n", "\r")):
            raise BuildError("mount/environment paths cannot contain colons, commas, or newlines")
    command = [
        "podman", "run", "-d", "--name", name, "--pull", "never", "--read-only",
        "--read-only-tmpfs=false", "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
        "--userns", f"keep-id:uid={APP_UID},gid={APP_GID}", "--user", f"{APP_UID}:{APP_GID}",
        "--pids-limit", "256", "--memory", "512m", "--memory-swap", "512m", "--cpus", "1",
        "--publish", "127.0.0.1:8088:8080", "--env-file", str(env_file),
        "--volume", f"{data}:/var/lib/honenode:rw,Z",
        "--tmpfs", "/tmp:rw,nosuid,nodev,noexec,size=64m,mode=1777",
    ]
    if broker_dir is None:
        # Podman 6.1 rejects tmpfs uid/gid options; the app only looks for a socket here.
        command += ["--tmpfs", "/run/honenode:rw,nosuid,nodev,noexec,size=1m,mode=0755"]
    else:
        # No relabel of a host broker directory. SELinux/socket access needs operator review.
        command += ["--volume", f"{broker_dir}:/run/honenode:ro", "--group-add", "keep-groups"]
    for value in (
        "HONE_BIND=0.0.0.0:8080", "HONE_STATIC_DIR=/app/static",
        "HONE_REGISTRY=/var/lib/honenode/registry/registry.db",
        "HONE_TENANT_DATA=/var/lib/honenode/tenants",
        "HONE_BROKER_SOCKET=/run/honenode/broker.sock", "HONE_TENANTS=t91,t92",
        "HONE_PANEL_DOMAIN=localhost", "HONE_TENANT_DOMAIN=honenode-preview.invalid",
        "HONE_SECURE_COOKIES=false", "HONE_LOG_FORMAT=json", "HONE_THEME=sharpnode",
        "HONE_API_TOKENS=",
    ):
        command += ["--env", value]
    return command + [image]


def launch(*, image: str = DEFAULT_IMAGE, name: str = "honenode-preview",
           archive: Path | None = None, bootstrap_env: Path | None = None,
           broker_dir: Path | None = None, run_dir: Path = RUN_DIR,
           runner: Runner = subprocess.run) -> str:
    if os.geteuid() == 0:
        raise BuildError("run as your ordinary user, not root or sudo")
    if not re.fullmatch(r"localhost/[a-z0-9]+(?:[._/-][a-z0-9]+)*:[A-Za-z0-9_][A-Za-z0-9_.-]*", image):
        raise BuildError("--image must be a tagged localhost/ image; no remote pulls are permitted")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", name):
        raise BuildError("invalid container name")
    rootless = run(["podman", "info", "--format", "{{.Host.Security.Rootless}}"], runner=runner).stdout.strip()
    if rootless != "true":
        raise BuildError("Podman must report a rootless engine (remote/rootful engines are unsupported)")
    # Reject remote mode: bind sources and bootstrap secrets must stay on this host.
    connection = run(["podman", "info", "--format", "{{.Host.ServiceIsRemote}}"], runner=runner).stdout.strip()
    if connection != "false":
        raise BuildError("a local Podman engine is required; remote connections are unsupported")
    if broker_dir is not None:
        broker_dir = broker_directory(broker_dir)
    if archive is not None:
        no_symlink_path(archive)
        if not archive.is_file():
            raise BuildError("--archive must be a regular non-symlink OCI archive")
        run(["podman", "load", "--input", str(archive.absolute())], runner=runner)
    data, env_file = prepare_state(run_dir.absolute(), bootstrap_env)
    command = podman_command(image=image, name=name, data=data, env_file=env_file, broker_dir=broker_dir)
    try:
        return run(command, runner=runner).stdout.strip()
    except BuildError as error:
        raise BuildError(
            f"{error}\n"
            "A failed start can leave a container behind; nothing was automatically replaced or removed.\n"
            f"Inspect first: podman container inspect {name}\n"
            f"Check logs: podman logs --tail 80 {name}\n"
            "Only if you confirm this is your disposable preview, stop/remove it before retrying:\n"
            f"  podman stop --time 10 {name}\n"
            f"  podman rm {name}\n"
            "Otherwise choose another --name (host port 8088 must still be free). "
            "Keep packaging/.local-run state."
        ) from error


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="optional local OCI archive to podman load first")
    parser.add_argument("--image", default=DEFAULT_IMAGE)
    parser.add_argument("--name", default="honenode-preview")
    parser.add_argument("--bootstrap-env", type=Path, help="optional private mode-0600 file with account/password")
    parser.add_argument("--broker-dir", type=Path, help="explicit, operator-reviewed host broker directory (not relabelled)")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        container = launch(image=args.image, name=args.name, archive=args.archive,
                           bootstrap_env=args.bootstrap_env, broker_dir=args.broker_dir)
    except (BuildError, OSError, UnicodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print(f"detached container: {container}")
    print("App preview requested at http://127.0.0.1:8088; inspect podman logs before sign-in.")
    print(f"Initial credentials: {RUN_DIR / 'bootstrap.env'} (not printed; reused on restart).")
    if args.broker_dir is None:
        print("APP-ONLY PREVIEW: broker unavailable; provisioning is NOT live. t91,t92 are reserved lab IDs only.")
    else:
        print("Broker directory mounted explicitly; connectivity, SELinux, policy and provisioning are NOT verified.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
